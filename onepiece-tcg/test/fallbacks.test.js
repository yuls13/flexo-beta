test('detectBlock : Cloudflare, Wordfence, API WordPress fermée', () => {
  const h = (o) => ({ get: (k) => o[k.toLowerCase()] ?? null });
  assert.equal(detectBlock(403, h({ server: 'cloudflare' }), '<title>Just a moment...</title>'), 'protection anti-robots Cloudflare');
  assert.equal(detectBlock(503, h({ server: 'cloudflare' }), ''), 'bloqué par Cloudflare');
  assert.equal(detectBlock(403, h({}), 'Generated by Wordfence'), 'bloqué par le pare-feu Wordfence');
  assert.equal(detectBlock(401, h({}), '{"code":"rest_not_logged_in"}'), 'API WordPress désactivée pour le public');
  assert.equal(detectBlock(503, h({ server: 'o2switch-PowerBoost-v3' }), 'Test de sécurité'), 'protection anti-robots de l’hébergeur o2switch');
  assert.equal(detectBlock(503, h({ server: 'nginx' }), 'Security check... Please turn JavaScript on and reload the page.'), 'protection anti-robots (test JavaScript)');
  assert.equal(detectBlock(503, h({ server: 'nginx' }), 'Maintenance en cours'), null);
  assert.equal(detectBlock(404, h({}), ''), null);
});

