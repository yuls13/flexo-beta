test('parseJsonLd : fiche produit et liste', () => {
  const html = `<script type="application/ld+json">{"@context":"https://schema.org","@graph":[{"@type":"Product","name":"Display OP-17 JP","url":"/p/op17","offers":{"@type":"Offer","price":"109.90","availability":"https://schema.org/PreOrder"}}]}</script>
  <script type="application/ld+json">{"@type":"ItemList","itemListElement":[{"@type":"ListItem","item":{"@type":"Product","name":"Booster OP-17","offers":[{"price":5.5,"availability":"OutOfStock"}]}}]}</script>`;
  const items = parseJsonLd(html, 'https://shop.fr/search');
  assert.equal(items.length, 2);
  assert.deepEqual([items[0].price, items[0].preorder, items[0].url], [109.9, true, 'https://shop.fr/p/op17']);
  assert.deepEqual([items[1].price, items[1].available], [5.5, false]);
});

