test('explain : raisons lisibles', () => {
  const [s] = compileSeries([{ id: 'OP16', queries: [], match: ['\\bOP-?16\\b'] }]);
  assert.equal(explain('OP16-118 Luffy SEC', s, 50).reason, 'carte à l’unité');
  assert.equal(explain('Display OP15 FR', s, 120).reason, 'pas la série OP16');
  assert.equal(explain('Display OP16 FR', s, null).reason, 'prix absent ou nul sur la boutique');
  assert.equal(explain('Carte One Piece Shanks OP16-020 L', s, 0).reason, 'carte à l’unité');
  assert.equal(explain('Display OP16 FR', s, 130).ok, true);
});

test('searchShop : API WooCommerce fermée (401) → repli sur la page de recherche, méthode mémorisée', async () => {
  const realFetch = globalThis.fetch;
  const calls = [];
  globalThis.fetch = async (url) => {
    calls.push(String(url));
    if (String(url).includes('/wp-json/')) return new Response('{"code":"rest_not_logged_in"}', { status: 401 });
    return new Response(WOO_HTML, { status: 200, headers: { 'content-type': 'text/html' } });
  };
  try {
    const shop = { id: 'ludo', domain: 'ludo-test.fr', base: 'https://ludo-test.fr', platform: 'woocommerce' };
    const { result, trace } = await withTrace(() => searchShop(shop, 'OP16'));
    assert.equal(result.strategy, 'wooHtml');
    assert.equal(result.items.length, 2);
    assert.equal(trace[0].status, 401);
    assert.equal(trace[0].note, 'API WordPress désactivée pour le public');
    calls.length = 0;
    await searchShop(shop, 'Bataille Décisive');
    assert.equal(calls.length, 1); // méthode qui marche essayée en premier
    assert.match(calls[0], /\?s=/);
    // Page de recherche vide (aucune méthode mémorisée) : l'API refusée (401) n'est pas réessayée.
    const shop2 = { id: 'ludo2', domain: 'ludo2-test.fr', base: 'https://ludo2-test.fr', platform: 'woocommerce' };
    globalThis.fetch = async (url) => {
      calls.push(String(url));
      if (String(url).includes('/wp-json/')) return new Response('{"code":"rest_not_logged_in"}', { status: 401 });
      return new Response('<title>Vous avez cherché OP17</title>', { status: 200, headers: { 'content-type': 'text/html' } });
    };
    calls.length = 0;
    await searchShop(shop2, 'OP17');
    await searchShop(shop2, 'OP-17');
    assert.equal(calls.filter((u) => u.includes('/wp-json/')).length, 1);
  } finally {
    globalThis.fetch = realFetch;
  }
});

test('searchShop : tout bloqué → erreur explicite', async () => {
  const realFetch = globalThis.fetch;
  globalThis.fetch = async () => new Response('<title>Just a moment...</title>', { status: 403, headers: { server: 'cloudflare' } });
  try {
    const shop = { id: 'x', domain: 'cf-test.fr', base: 'https://cf-test.fr', platform: 'prestashop' };
    await assert.rejects(searchShop(shop, 'OP16'), /Cloudflare/);
    assert.ok(PLATFORM_STRATEGIES.auto.length >= 6);
  } finally {
    globalThis.fetch = realFetch;
  }
});

